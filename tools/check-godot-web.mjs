import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.argv[2] || 'http://127.0.0.1:9544/godot-demo/';
const output = process.env.GODOT_ARTIFACTS || 'artifacts/godot-web-review';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_BIN });
try {
  for (const variant of ['desktop', 'mobile', 'landscape']) {
    const mobile = variant !== 'desktop';
    const viewport = variant === 'landscape' ? { width: 844, height: 390 } : mobile ? { width: 390, height: 844 } : { width: 1440, height: 900 };
    const context = await browser.newContext({ viewport, deviceScaleFactor: mobile ? 2 : 1, isMobile: mobile, hasTouch: mobile });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
    const entrance = new URL('../', base);
    entrance.search = '?debug&v=20261001-fullbody-dev4';
    entrance.hash = 'entrance-check';
    await page.goto(entrance.href);
    await page.waitForFunction(() => window.godotCampaignReady || window.godotSampleReady, { timeout: 30000 });
    assert.match(page.url(), /godot-demo\/\?debug&v=20261001-fullbody-dev4#entrance-check/, 'root must open the same new game and preserve query/hash');
    assert.equal(await page.getByRole('link', { name: '旧版', exact: true }).count(), 0);
    assert.equal(await page.evaluate(() => window.godotCampaignReady === true), true, 'default development entrance must open actual campaign, not only animation sample');
    await page.screenshot({ path: output + '/' + variant + '-home.png' });
    await page.getByRole('button', { name: '设置', exact: true }).click();
    await page.getByRole('button', { name: '音效 · 开启', exact: true }).click();
    await page.getByRole('button', { name: '节能 · 60 帧上限', exact: true }).click();
    await page.waitForTimeout(5500);
    await page.reload();
    await page.waitForFunction(() => window.godotCampaignReady, { timeout: 30000 });
    assert.equal(await page.evaluate(() => window.campaignState.sound), false, 'sound setting must persist through actual browser reload');
    assert.equal(await page.evaluate(() => window.campaignState.fps), 60, 'render cap must persist through actual browser reload');
    await page.getByRole('button', { name: '进入学院', exact: true }).click();
    assert.equal(await page.locator('.level-pin .flag svg').count(), 6, 'all road markers use scalable illustrated crests, not flat clipped boxes');
    assert.equal(await page.locator('.level-pin .pin-stars svg').count(), 3);
    for (const marker of await page.locator('.level-pin').all()) {
      const box = await marker.boundingBox();
      assert(box.width >= 44 && box.height >= 44, 'map markers remain comfortable touch targets');
    }
    await page.screenshot({ path: output + '/' + variant + '-map.png' });
    await page.locator('[data-action="replay"]').click();
    await page.locator('[data-action="replay:2_intro"]').click();
    await page.waitForSelector('.comic-page');
    await page.getByRole('button', { name: '展开全页', exact: true }).click();
    await page.getByRole('button', { name: '继续', exact: true }).click();
    await page.waitForSelector('.archive-list');
    await page.getByRole('button', { name: '关闭', exact: true }).click();
    await page.locator('[data-level="1"]').click();
    await page.waitForSelector('.brief-road');
    assert.match(await page.locator('.brief-road').getAttribute('src'), /campus/);
    await page.getByRole('button', { name: '出发', exact: true }).click();
    await page.waitForSelector('.comic-page');
    assert.equal(await page.locator('.comic-panel.revealed').count(), 1);
    await page.locator('.comic-page').click({ position: { x: 8, y: 8 } });
    assert.equal(await page.locator('.comic-panel.revealed').count(), 5, 'first click must reveal all without advancing');
    const comicGeometry = await page.evaluate(() => {
      const art = document.querySelector('.comic-art');
      const projection = art.getScreenCTM?.();
      const panels = document.querySelector('.comic-panels').getBoundingClientRect();
      const footer = document.querySelector('.comic-footer').getBoundingClientRect();
      return { uniform: !!projection && Math.abs(projection.a - projection.d) < 0.001, panelsBottom: panels.bottom, footerTop: footer.top };
    });
    assert.equal(comicGeometry.uniform, true, 'comic artwork must preserve original proportions rather than squash characters');
    assert.ok(comicGeometry.panelsBottom <= comicGeometry.footerTop + 1, 'comic reading area must not sit underneath continue buttons');
    assert.equal(await page.locator('.comic-art image:not([clip-path])').count(), 0, 'each cell must clip neighboring painted panels');
    await page.screenshot({ path: output + '/' + variant + '-comic.png' });
    await page.getByRole('button', { name: '继续', exact: true }).click();
    await page.waitForFunction(() => window.campaignState?.mode === 'play');
    if (mobile) {
      const canvas = await page.locator('#canvas').boundingBox();
      for (const id of ['left', 'right', 'down', 'jump']) {
        const key = await page.locator('#' + id).boundingBox();
        assert(key.width >= 44 && key.height >= 44, 'touch targets need real 44px minimum');
        assert(key.y >= canvas.y + canvas.height || key.x + key.width <= canvas.x || key.x >= canvas.x + canvas.width, 'touch buttons may not obstruct gameplay canvas');
      }
      const session = await context.newCDPSession(page);
      const right = await page.locator('#right').boundingBox();
      const jump = await page.locator('#jump').boundingBox();
      const first = { x: right.x + right.width / 2, y: right.y + right.height / 2, id: 1 };
      const second = { x: jump.x + jump.width / 2, y: jump.y + jump.height / 2, id: 2 };
      await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [first] });
      await page.waitForTimeout(650);
      const y = await page.evaluate(() => window.campaignState.y);
      await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [first, second] });
      await page.waitForTimeout(180);
      assert((await page.evaluate(() => window.campaignState.energy)) < 99, 'held forward touch must sprint');
      assert((await page.evaluate(() => window.campaignState.y)) < y - 20, 'second simultaneous touch must jump');
      await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    } else {
      assert.equal(await page.locator('#dpad').isVisible(), false);
      await page.keyboard.down('ArrowRight');
      await page.waitForTimeout(650);
      await page.keyboard.down('Space');
      await page.waitForTimeout(120);
      assert((await page.evaluate(() => window.campaignState.energy)) < 99);
      await page.keyboard.up('Space');
      await page.keyboard.up('ArrowRight');
    }
    await page.screenshot({ path: output + '/' + variant + '-play.png' });
    await page.locator('#pause').click();
    await page.waitForFunction(() => window.campaignState.mode === 'pause');
    const before = await page.evaluate(() => window.campaignState.elapsed);
    await page.waitForTimeout(200);
    assert.equal(await page.evaluate(() => window.campaignState.elapsed), before, 'pause must freeze real simulation');
    await page.screenshot({ path: output + '/' + variant + '-pause.png' });
    await page.getByRole('button', { name: '学院地图', exact: true }).click();
    await page.waitForSelector('.map-plane');
    await page.locator('[data-level="3"]').click();
    assert.match(await page.locator('.brief-road').getAttribute('src'), /night-market/);
    await page.screenshot({ path: output + '/' + variant + '-brief.png' });
    await page.getByRole('button', { name: '出发', exact: true }).click();
    await page.getByRole('button', { name: '跳过', exact: true }).click();
    await page.waitForFunction(() => window.campaignState.mode === 'play' && window.campaignState.chapter === 3);
    await page.waitForTimeout(300);
    await page.screenshot({ path: output + '/' + variant + '-night-play.png' });
    assert.deepEqual(errors, []);
    console.log(variant.toUpperCase() + ': actual persistence, archive, map/road brief, comic geometry, multitouch/pause and non-obstructing controls passed');
    await context.close();
  }
  const context = await browser.newContext();
  await context.addInitScript(() => Object.defineProperty(window, 'indexedDB', { value: { open() { throw new DOMException('Storage intentionally disabled for regression', 'SecurityError'); } } }));
  const page = await context.newPage();
  await page.goto(base + '?debug&v=storage-disabled');
  await page.waitForFunction(() => window.godotCampaignReady, { timeout: 30000 });
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByRole('button', { name: '节能 · 60 帧上限', exact: true }).click();
  await page.waitForSelector('.save-notice');
  await page.getByRole('button', { name: '返回', exact: true }).click();
  await page.getByRole('button', { name: '进入学院', exact: true }).click();
  await page.locator('[data-level="1"]').click();
  await page.getByRole('button', { name: '出发', exact: true }).click();
  await page.getByRole('button', { name: '跳过', exact: true }).click();
  await page.waitForFunction(() => window.campaignState.mode === 'play');
  console.log('DISABLED STORAGE: visible save warning and continued real gameplay passed');
  await context.close();
} finally { await browser.close(); }
